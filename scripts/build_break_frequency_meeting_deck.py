def read_csv_rows(path: Path) -> list[dict[str, str]]:
    import csv

    if not path.exists():
        return []
    with path.open(newline="") as f:
        return list(csv.DictReader(f))


def load_dylan_maps() -> tuple[dict[str, float], dict[str, float]]:
    k_map: dict[str, float] = {}
    for row in read_csv_rows(DYLAN_K_CSV):
        try:
            k_map[row["event"]] = float(row["dylan_k"])
        except Exception:
            pass

    nmap_map: dict[str, float] = {}
    for row in read_csv_rows(DYLAN_NMAP_CSV):
        if row.get("source_owner") != "dylan_thesis":
            continue
        try:
            nmap_map[row["event"]] = float(row["nmap_value"])
        except Exception:
            try:
                nmap_map[row["event"]] = float(row["nmap"])
            except Exception:
                pass
    return k_map, nmap_map


def clean_float(value, digits=4) -> str:
    if value is None:
        return "unavailable"
    try:
        val = float(value)
    except Exception:
        return str(value)
    if not math.isfinite(val):
        return "unavailable"
    if abs(val) >= 1e4 or (abs(val) < 1e-3 and val != 0):
        return f"{val:.{digits}e}"
    return f"{val:.{digits}g}"


def get_mtime(path: Path) -> dt.datetime | None:
    if not path.exists():
        return None
    return dt.datetime.fromtimestamp(path.stat().st_mtime)


def is_new_weighted_spectral(run_dir: Path) -> bool:
    spectral = run_dir / "spectral_plot.pdf"
    if not spectral.exists():
        return False
    if (run_dir / "spectral_breaks_eats_weighted.csv").exists():
        return True
    mtime = get_mtime(spectral)
    return bool(mtime and mtime >= UPDATED_AFTER)


def read_best_json(run_dir: Path) -> dict:
    candidates = [
        run_dir / "minimized/minimized.json",
        run_dir / "minimized.json",
        run_dir / "best_fit.json",
        run_dir / "results.json",
    ]
    for path in candidates:
        if path.exists():
            try:
                return json.loads(path.read_text())
            except Exception:
                continue
    return {}


def read_toml(run_dir: Path) -> dict:
    for name in ("model.toml", "config.toml"):
        path = run_dir / name
        if path.exists():
            try:
                return tomllib.loads(path.read_text())
            except Exception:
                return {}
    return {}


def get_param(data: dict, name: str):
    params = data.get("params") or {}
    model = params.get("model") or {}
    if name in model:
        return model[name]
    if name in data:
        return data[name]
    return None


def get_sampler_summary(toml_data: dict) -> str:
    sampler = toml_data.get("sampler") or {}
    if not sampler:
        return "Sampler settings unavailable in TOML."
    fields = []
    for key in ("name", "ntemps", "num_walkers", "burn_length", "run_length", "workers"):
        if key in sampler:
            fields.append(f"{key}={sampler[key]}")
    return ", ".join(fields) if fields else "Sampler settings unavailable in TOML."


def render_pdf_first_page(src: Path) -> Path | None:
    if not src.exists():
        return None
    if src.suffix.lower() in {".png", ".jpg", ".jpeg"}:
        return crop_image_margins(src)
    CACHE.mkdir(parents=True, exist_ok=True)
    stat = src.stat()
    key = hashlib.sha1(f"{src}:{stat.st_mtime_ns}:{stat.st_size}".encode()).hexdigest()[:20]
    out_stem = CACHE / key
    out_png = CACHE / f"{key}.png"
    cropped = CACHE / f"{key}_cropped.png"
    if cropped.exists():
        return cropped
    cmd = [
        "pdftoppm",
        "-f",
        "1",
        "-l",
        "1",
        "-singlefile",
        "-png",
        "-r",
        "130",
        str(src),
        str(out_stem),
    ]
    try:
        subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        return crop_image_margins(out_png) if out_png.exists() else None
    except Exception:
        return None


def crop_image_margins(src: Path) -> Path | None:
    """Crop near-white margins so source figures are readable on slides."""
    if not src.exists():
        return None
    CACHE.mkdir(parents=True, exist_ok=True)
    stat = src.stat()
    key = hashlib.sha1(f"crop:{src}:{stat.st_mtime_ns}:{stat.st_size}".encode()).hexdigest()[:20]
    out = CACHE / f"{key}_cropped.png"
    if out.exists():
        return out
    try:
        img = Image.open(src).convert("RGB")
        bg = Image.new("RGB", img.size, (255, 255, 255))
        diff = ImageChops.difference(img, bg).convert("L")
        mask = diff.point(lambda p: 255 if p > 12 else 0)
        bbox = mask.getbbox()
        if not bbox:
            img.save(out)
            return out
        pad = 18
        left = max(bbox[0] - pad, 0)
        top = max(bbox[1] - pad, 0)
        right = min(bbox[2] + pad, img.size[0])
        bottom = min(bbox[3] + pad, img.size[1])
        cropped = img.crop((left, top, right, bottom))
        cropped.save(out)
        return out
    except Exception:
        return src


def add_header(fig, title: str, subtitle: str | None = None):
    fig.text(0.035, 0.955, title, fontsize=22, fontweight="bold", ha="left", va="top")
    if subtitle:
        fig.text(0.035, 0.915, subtitle, fontsize=10.5, color="#444444", ha="left", va="top")


def add_footer(fig, text: str):
    fig.text(0.985, 0.018, text, fontsize=7.5, color="#666666", ha="right", va="bottom")


def add_text_box(fig, rect, text: str, title: str | None = None, fontsize=12, face="#f7f7f7"):
    ax = fig.add_axes(rect)
    ax.set_axis_off()
    ax.add_patch(plt.Rectangle((0, 0), 1, 1, facecolor=face, edgecolor="#999999", linewidth=1.2))
    y = 0.93
    if title:
        ax.text(0.04, y, title, fontsize=fontsize + 2, fontweight="bold", ha="left", va="top")
        y -= 0.1
    wrapped = []
    for para in text.split("\n"):
        if para.strip():
            wrapped.extend(textwrap.wrap(para, width=78))
        else:
            wrapped.append("")
    ax.text(0.04, y, "\n".join(wrapped), fontsize=fontsize, ha="left", va="top", color="#222222")


def add_image_box(fig, rect, src: Path | None, label: str, missing_text: str | None = None, fill: bool = False):
    ax = fig.add_axes(rect)
    ax.set_axis_off()
    ax.text(0.0, 1.02, label, fontsize=12, fontweight="bold", ha="left", va="bottom", transform=ax.transAxes)
    if src is None or not src.exists():
        ax.add_patch(plt.Rectangle((0, 0), 1, 1, facecolor="#f6f6f6", edgecolor="#aaaaaa", linewidth=1.2))
        msg = missing_text or "Missing product"
        ax.text(0.5, 0.5, "\n".join(textwrap.wrap(msg, width=52)), fontsize=13, color="#777777", ha="center", va="center")
        return

    rendered = render_pdf_first_page(src)
    if rendered is None or not rendered.exists():
        ax.add_patch(plt.Rectangle((0, 0), 1, 1, facecolor="#fff4f4", edgecolor="#aa7777", linewidth=1.2))
        ax.text(0.5, 0.5, f"Could not render:\n{src.name}", fontsize=12, color="#884444", ha="center", va="center")
        return
    try:
        img = Image.open(rendered).convert("RGB")
        ax.imshow(img, aspect="auto" if fill else None)
    except Exception as exc:
        ax.add_patch(plt.Rectangle((0, 0), 1, 1, facecolor="#fff4f4", edgecolor="#aa7777", linewidth=1.2))
        ax.text(0.5, 0.5, f"Could not load image:\n{exc}", fontsize=12, color="#884444", ha="center", va="center")


def make_slide(pdf: PdfPages, title: str, subtitle: str | None = None):
    fig = plt.figure(figsize=PAGE_SIZE, facecolor="white")
    add_header(fig, title, subtitle)
    return fig


def save_slide(pdf: PdfPages, fig):
    pdf.savefig(fig, bbox_inches="tight")
    plt.close(fig)


def discover_entries():
    dylan_k, dylan_nmap = load_dylan_maps()
    entries: list[dict] = []
    skipped: list[dict] = []

    for fit in FIT_CATALOG:
        root = fit["run_root"]
        if not root.exists():
            skipped.append({**fit, "grb": "*", "reason": "run root missing"})
            continue
        for run_dir in sorted(p for p in root.iterdir() if p.is_dir()):
            grb = run_dir.name
            spectral = run_dir / "spectral_plot.pdf"
            if not spectral.exists():
                skipped.append({**fit, "grb": grb, "reason": "spectral_plot.pdf missing"})
                continue
            if not is_new_weighted_spectral(run_dir):
                skipped.append({**fit, "grb": grb, "reason": "new EATS-weighted spectral plot not finished"})
                continue

            best = read_best_json(run_dir)
            toml_data = read_toml(run_dir)
            nmap = best.get("nmap")
            k_val = get_param(best, "k")
            entries.append(
                {
                    **fit,
                    "grb": grb,
                    "run_dir": run_dir,
                    "spectral": spectral,
                    "legacy_spectral": run_dir / "spectral_plot_legacy_before_eats_weighted.pdf",
                    "light_curve": run_dir / "light_curve.pdf",
                    "ampy_comparison": run_dir / "ampy_comparison.pdf",
                    "corner": run_dir / "corner.pdf",
                    "corner_np": run_dir / "corner_np.pdf",
                    "mass_profile": run_dir / "mass_profile.pdf",
                    "nmap": nmap,
                    "dylan_nmap": dylan_nmap.get(grb),
                    "k": k_val,
                    "dylan_k": dylan_k.get(grb),
                    "sampler": get_sampler_summary(toml_data),
                    "mtime": get_mtime(spectral),
                }
            )

    # Use Dylan thesis order where available, then alphabetical.
    dylan_order = [row.get("event") for row in read_csv_rows(DYLAN_K_CSV)]
    order_index = {event: i for i, event in enumerate(dylan_order) if event}
    entries.sort(key=lambda e: (order_index.get(e["grb"], 10_000), e["grb"], e["fit_type"]))
    skipped.sort(key=lambda e: (order_index.get(e.get("grb", ""), 10_000), e.get("grb", ""), e["fit_type"]))
    return entries, skipped


def title_text(entry: dict) -> str:
    delta = None
    if entry.get("nmap") is not None and entry.get("dylan_nmap") is not None:
        delta = float(entry["nmap"]) - float(entry["dylan_nmap"])
    return "\n".join(
        [
            f"Fit type: {entry['display']}",
            f"Run folder: {entry['run_dir'].name}",
            "",
            f"Our nmap: {clean_float(entry.get('nmap'))}",
            f"Dylan thesis/tracking-sheet nmap: {clean_float(entry.get('dylan_nmap'))}",
            f"Delta nmap (ours - Dylan): {clean_float(delta)}   [more negative nmap is better in these files]",
            "",
            f"Our k: {clean_float(entry.get('k'))}",
            f"Dylan k: {clean_float(entry.get('dylan_k'))}",
            "",
            f"Sampler: {entry.get('sampler')}",
            "",
            entry["method"],
        ]
    )


def add_status_slide(pdf: PdfPages, entries: list[dict], skipped: list[dict]):
    fig = make_slide(
        pdf,
        "Spectral Break Recalculation Status",
        "EATS = Equal-Arrival-Time Surface. Deck built from completed EATS-weighted spectral products only.",
    )
    counts = {}
    for entry in entries:
        counts[entry["display"]] = counts.get(entry["display"], 0) + 1
    skipped_counts = {}
    for item in skipped:
        if item["reason"] == "new EATS-weighted spectral plot not finished":
            skipped_counts[item["display"]] = skipped_counts.get(item["display"], 0) + 1

    lines = [
        "Interpretation point: the old spectral-break diagnostic was a local/legacy calculation and is probably not suitable for physical interpretation of nu_a, nu_m, and nu_c.",
        "The new plots use the Dylan-style EATS calculation, where EATS means Equal-Arrival-Time Surface.",
        "",
        "Included completed weighted plots:",
    ]
    if counts:
        for name, count in sorted(counts.items()):
            lines.append(f"- {name}: {count}")
    else:
        lines.append("- none")
    lines.extend(["", "Skipped because the new weighted spectral plot was not finished yet:"])
    if skipped_counts:
        for name, count in sorted(skipped_counts.items()):
            lines.append(f"- {name}: {count}")
    else:
        lines.append("- none")
    lines.extend(
        [
            "",
            "Caveat: Dylan thesis light-curve and spectral-break panels were not found as standalone local files during this build. Placeholder panels are included so the deck structure is ready once those panels are added.",
        ]
    )
    add_text_box(fig, [0.08, 0.12, 0.84, 0.72], "\n".join(lines), fontsize=13)
    add_footer(fig, f"Built {dt.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    save_slide(pdf, fig)


