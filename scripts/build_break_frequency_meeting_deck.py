def write_manifest(entries: list[dict], skipped: list[dict]):
    included_lines = [
        "| GRB | Fit type | nmap | Dylan nmap | k | Dylan k | spectral mtime | run folder |",
        "| --- | --- | ---: | ---: | ---: | ---: | --- | --- |",
    ]
    for e in entries:
        included_lines.append(
            "| {grb} | {display} | {nmap} | {dnmap} | {k} | {dk} | {mtime} | `{run}` |".format(
                grb=e["grb"],
                display=e["display"],
                nmap=clean_float(e.get("nmap")),
                dnmap=clean_float(e.get("dylan_nmap")),
                k=clean_float(e.get("k")),
                dk=clean_float(e.get("dylan_k")),
                mtime=e["mtime"].strftime("%Y-%m-%d %H:%M:%S") if e.get("mtime") else "unavailable",
                run=e["run_dir"],
            )
        )

    skipped_lines = [
        "| GRB | Fit type | Reason | run root |",
        "| --- | --- | --- | --- |",
    ]
    for s in skipped:
        if s["reason"] != "new EATS-weighted spectral plot not finished":
            continue
        skipped_lines.append(f"| {s.get('grb')} | {s['display']} | {s['reason']} | `{s['run_root']}` |")

    text = "\n".join(
        [
            "# Break-Frequency Meeting Deck Manifest",
            "",
            f"Built: {dt.datetime.now().isoformat(timespec='seconds')}",
            f"Deck: `{OUT_PDF}`",
            "",
            "Selection rule: include a run only if `spectral_plot.pdf` was modified after "
            f"{UPDATED_AFTER.isoformat(sep=' ')} or if `spectral_breaks_eats_weighted.csv` exists.",
            "",
            "Definition: EATS = Equal-Arrival-Time Surface.",
            "",
            "Important caveat: most old legacy spectral-break plots were overwritten by the batch updater without a backup. "
            "Only folders with `spectral_plot_legacy_before_eats_weighted.pdf` have true old-vs-new visual comparison slides.",
            "",
            "## Included",
            "",
            "\n".join(included_lines),
            "",
            "## Skipped Because Weighted Plot Was Not Finished",
            "",
            "\n".join(skipped_lines),
            "",
        ]
    )
    OUT_MANIFEST.write_text(text)


def main():
    entries, skipped = discover_entries()
    build_deck(entries, skipped)
    write_manifest(entries, skipped)
    print(f"wrote {OUT_PDF}")
    print(f"wrote {OUT_MANIFEST}")
    print(f"included {len(entries)} fit products; skipped {len(skipped)}")


if __name__ == "__main__":
    main()
